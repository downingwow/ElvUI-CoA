$ErrorActionPreference = "Stop"

$AddonRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProfilesFolder = Join-Path $AddonRoot "profiles"
$OutputFile = Join-Path $AddonRoot "Profiles.lua"

if (-not (Test-Path -LiteralPath $ProfilesFolder)) {
    New-Item -ItemType Directory -Path $ProfilesFolder | Out-Null
}

function ConvertTo-LuaQuotedString([string]$Value) {
    if ($null -eq $Value) { return '""' }
    $Value = $Value.Replace('\', '\\')
    $Value = $Value.Replace('"', '\"')
    $Value = $Value.Replace("`r", '\r')
    $Value = $Value.Replace("`n", '\n')
    return '"' + $Value + '"'
}

function ConvertTo-LuaLongString([string]$Value) {
    $Equals = ""
    while ($Value.Contains("]" + $Equals + "]")) {
        $Equals += "="
    }
    return "[" + $Equals + "[" + $Value + "]" + $Equals + "]"
}

$Files = @(Get-ChildItem -LiteralPath $ProfilesFolder -File -Filter "*.txt" | Sort-Object Name)
$Builder = New-Object System.Text.StringBuilder

[void]$Builder.AppendLine("-- AUTO-GENERATED FILE")
[void]$Builder.AppendLine("-- Generated by GenerateProfiles.bat / GenerateProfiles.ps1")
[void]$Builder.AppendLine("-- Do not edit this file manually; edit the .txt files in profiles instead.")
[void]$Builder.AppendLine("")
[void]$Builder.AppendLine("ElvUI_ProfileInstaller_Profiles = {")

$Count = 0
foreach ($File in $Files) {
    $Code = [System.IO.File]::ReadAllText($File.FullName).Trim()
    if ([string]::IsNullOrWhiteSpace($Code)) {
        Write-Warning "Skipping empty file: $($File.Name)"
        continue
    }

    $ProfileName = [System.IO.Path]::GetFileNameWithoutExtension($File.Name).Trim()
    if ([string]::IsNullOrWhiteSpace($ProfileName)) {
        Write-Warning "Skipping file with an empty profile name: $($File.Name)"
        continue
    }

    $LuaName = ConvertTo-LuaQuotedString $ProfileName
    $LuaFile = ConvertTo-LuaQuotedString $File.Name
    $LuaCode = ConvertTo-LuaLongString $Code

    [void]$Builder.AppendLine("    {")
    [void]$Builder.AppendLine("        name = $LuaName,")
    [void]$Builder.AppendLine("        file = $LuaFile,")
    [void]$Builder.AppendLine("        code = $LuaCode,")
    [void]$Builder.AppendLine("    },")
    $Count++
}

[void]$Builder.AppendLine("}")
[void]$Builder.AppendLine("")

$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($OutputFile, $Builder.ToString(), $Utf8NoBom)

Write-Host "Generated $Count profile(s)."
Write-Host "Output: $OutputFile"
